# ---------- a browser Windows has registered, whatever its name ----------

NIMBUS = RegisteredBrowser(name="Nimbus Web", exe=r"C:\Apps\Nimbus\nimbus.exe")
WAVE = RegisteredBrowser(name="@C:\\Apps\\Wave\\wave.exe,-100", app_id="Waveline.ABC123")


def _scan(browsers: list[RegisteredBrowser]) -> RawScan:
    return RawScan(
        start_apps=[
            StartApp(name="Nimbus", app_id=r"C:\Apps\Nimbus\nimbus.exe"),
            StartApp(name="Waveline", app_id="Waveline.ABC123"),
            StartApp(name="Calculator", app_id="Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"),
        ],
        programs=[InstalledProgram(name="Nimbus Web", exe=r"C:\Apps\Nimbus\nimbus.exe")],
        browsers=browsers,
    )


def test_without_registration_an_unknown_browser_name_is_not_caught() -> None:
    catalog = build_catalog(_scan([]), windows_dir=WINDOWS)
    assert all(a.blocked is None for a in catalog.apps)  # the control case


def test_a_registered_browser_is_blocked_by_program_appid_or_name() -> None:
    catalog = build_catalog(_scan([NIMBUS, WAVE]), windows_dir=WINDOWS)
    blocked = {a.name: a.blocked for a in catalog.apps}
    assert "registered as a web browser" in (blocked["Nimbus"] or "")  # same program
    assert "registered as a web browser" in (blocked["Waveline"] or "")  # same AppUserModelID
    assert blocked["Calculator"] is None
    by_name = RegisteredBrowser(name="Waveline")
    assert browser_match([by_name], name="waveline")
    assert browser_match([WAVE], name="Wave") is None  # "@resource" names are not names


def test_a_registered_browser_never_opens_even_if_always_allowed_and_the_file_says_ok() -> None:
    catalog = build_catalog(_scan([]), windows_dir=WINDOWS)  # catalog made before / tampered
    nimbus = next(a for a in catalog.apps if a.name == "Nimbus")
    assert nimbus.blocked is None
    allow_always(nimbus.id, nimbus.name, source="settings")
    starter = FakeStarter()
    launcher = AppLauncher(
        starter, load_allowlist(), catalog=lambda: catalog, browsers=lambda: [NIMBUS]
    )
    with pytest.raises(LaunchRefused, match="registered as a web browser"):
        launcher.ensure_running("Nimbus")
    assert starter.started == []


def test_an_always_allowed_gap_app_never_opens() -> None:
    catalog = Catalog(
        apps=build_catalog(
            RawScan(start_apps=[StartApp(name="Ollama", app_id=r"C:\o\Ollama\ollama app.exe")]),
            windows_dir=WINDOWS,
        ).apps
    )
    ollama = catalog.apps[0]
    assert ollama.blocked
    allow_always(ollama.id, ollama.name, source="wizard")
    starter = FakeStarter()
    launcher = AppLauncher(starter, load_allowlist(), catalog=lambda: catalog, browsers=list)
    with pytest.raises(LaunchRefused, match="never opens"):
        launcher.ensure_running("Ollama")
    ollama.blocked = None  # the catalog file is data: the launch checks again
    with pytest.raises(LaunchRefused, match="never opens"):
        launcher.ensure_running("Ollama")
    assert starter.started == []


